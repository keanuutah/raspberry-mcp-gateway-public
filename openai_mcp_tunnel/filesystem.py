"""Restricted Home Assistant YAML file operations.

Application-level restrictions. HA Supervisor mounts the whole config directory rw;
this program must not be treated as an OS-level filesystem sandbox.
"""
from __future__ import annotations
import datetime as dt
import difflib
import hashlib
import json
import os
import re
import stat
import fcntl
import hmac
import urllib.request
import urllib.error
import logging
from pathlib import Path
from unified_approval import unified_mode, read_approval, clear_approval

import yaml

ROOT = Path(os.environ.get('HA_CONFIG_ROOT', '/homeassistant_config'))
BACKUP_DIR = 'yaml_backups'
PACKAGE_DIR = 'packages'
READ_MAIN = frozenset(('configuration.yaml', 'automations.yaml', 'scripts.yaml'))
YAML_FILENAME = re.compile(r'^[a-zA-Z0-9][a-zA-Z0-9_-]{0,100}\.yaml$')
# Only backups generated by _commit_approved(): <package>_YYYY-MM-DD_HH-MM-SS_microseconds.yaml.bak.
BACKUP_FILENAME = re.compile(r'^[a-zA-Z0-9][a-zA-Z0-9_-]{0,100}_[0-9]{4}-[0-9]{2}-[0-9]{2}_[0-9]{2}-[0-9]{2}-[0-9]{2}_[0-9]{6}\.yaml\.bak$')
MAX_BYTES = 1024 * 1024
_LOG = logging.getLogger(__name__)


def digest(b: bytes) -> str:
    return hashlib.sha256(b).hexdigest()


def _open_dir(directory: Path) -> int:
    return os.open(str(directory), os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW)


def _read_at(fd: int, name: str) -> bytes:
    f = os.open(name, os.O_RDONLY | os.O_NOFOLLOW | os.O_NONBLOCK, dir_fd=fd)
    try:
        if not stat.S_ISREG(os.fstat(f).st_mode):
            raise ValueError('Nur reguläre Dateien sind erlaubt.')
        content = bytearray()
        while len(content) <= MAX_BYTES:
            chunk = os.read(f, min(65536, MAX_BYTES + 1 - len(content)))
            if not chunk:
                return bytes(content)
            content.extend(chunk)
        raise ValueError('Datei ist zu groß.')
    finally:
        os.close(f)


def _validate(name: str) -> str:
    if not isinstance(name, str) or not YAML_FILENAME.fullmatch(name):
        raise ValueError('Unzulässiger Dateiname; nur einfache *.yaml-Namen.')
    return name


def _validate_write_name(name: str) -> str:
    _validate(name)
    if name in READ_MAIN:
        raise PermissionError('Geschützter Home-Assistant-Hauptdateiname nicht schreibbar.')
    return name


def _syntax(content: str) -> None:
    if not isinstance(content, str) or len(content.encode('utf-8')) > MAX_BYTES:
        raise ValueError('Ungültiger Inhalt oder zu groß.')
    # BaseLoader accepts Home Assistant's custom YAML tags such as !secret and !include.
    # This is YAML syntax validation, NOT a full Home Assistant configuration check.
    yaml.compose(content, Loader=yaml.BaseLoader)


def list_packages() -> list[str]:
    with os.scandir(ROOT / PACKAGE_DIR) as entries:
        return sorted(e.name for e in entries if YAML_FILENAME.fullmatch(e.name) and e.is_file(follow_symlinks=False))


def read_yaml(name: str, area: str = PACKAGE_DIR) -> dict:
    _validate(name)
    if area == PACKAGE_DIR:
        directory = ROOT / PACKAGE_DIR
    elif area == 'main' and name in READ_MAIN:
        directory = ROOT
    else:
        raise ValueError('Lesezugriff auf diesen Pfad nicht erlaubt.')
    fd = _open_dir(directory)
    try:
        data = _read_at(fd, name)
    finally:
        os.close(fd)
    return {'path': f'{area}/{name}' if area != 'main' else name, 'sha256': digest(data), 'content': data.decode('utf-8')}


def plan_write(name: str, content: str) -> dict:
    _validate_write_name(name)
    _syntax(content)
    fd = _open_dir(ROOT / PACKAGE_DIR)
    try:
        try:
            old = _read_at(fd, name)
            exists = True
        except FileNotFoundError:
            old = b''
            exists = False
    finally:
        os.close(fd)
    new = content.encode('utf-8')
    return {
        'name': name, 'create': not exists, 'expected_sha256': digest(old) if exists else None,
        'proposed_sha256': digest(new),
        'diff': ''.join(difflib.unified_diff(old.decode('utf-8').splitlines(keepends=True), content.splitlines(keepends=True), fromfile=f'previous/{name}', tofile=f'proposed/{name}'))[:30000],
        'note': 'Nur Vorschau. Kein Schreibzugriff ohne aktiviertes WRITE_ENABLED, korrekte Hashes und ausdrückliche Benutzerfreigabe.'
    }


def _write_new_at(fd: int, name: str, data: bytes, mode: int = 0o600) -> None:
    out = os.open(name, os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW, mode, dir_fd=fd)
    try:
        with os.fdopen(out, 'wb', closefd=False) as stream:
            stream.write(data)
            stream.flush()
            os.fsync(out)
    finally:
        os.close(out)


def _open_backup_dir() -> int:
    """Backups require a pre-existing directory. Never create entries in config root.

    This is intentional: AppArmor must NOT grant directory write permissions
    on /homeassistant_config itself, even just to create yaml_backups.
    """
    root_fd = _open_dir(ROOT)
    try:
        try:
            bfd = os.open(BACKUP_DIR, os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW, dir_fd=root_fd)
        except FileNotFoundError as exc:
            raise FileNotFoundError(
                'Backup-Verzeichnis /config/yaml_backups/ fehlt. '
                'Vor der Schreibfreigabe einmalig manuell anlegen.'
            ) from exc
        if not stat.S_ISDIR(os.fstat(bfd).st_mode):
            os.close(bfd)
            raise ValueError('Backup-Pfad ist kein Verzeichnis.')
        return bfd
    finally:
        os.close(root_fd)


def verify_backup(name: str, expected_sha256: str | None = None) -> dict:
    """Read-only hash verification for one gateway-generated YAML backup.

    Does not return content or accept a path. Uses the existing no-follow
    directory descriptor and bounded regular-file reader. Never writes.
    """
    if not isinstance(name, str) or not BACKUP_FILENAME.fullmatch(name):
        raise ValueError('Nur einfache Gateway-Backup-Dateinamen (*.yaml.bak) erlaubt.')
    if expected_sha256 is not None and (
        not isinstance(expected_sha256, str) or
        re.fullmatch(r'[0-9a-f]{64}', expected_sha256) is None
    ):
        raise ValueError('Ungültiger erwarteter SHA256 (64 Kleinbuchstaben/Hex-Zeichen).')
    fd = _open_backup_dir()
    try:
        try:
            data = _read_at(fd, name)
        except FileNotFoundError:
            return {'name': name, 'exists': False, 'read_only': True}
    finally:
        os.close(fd)
    actual_sha256 = digest(data)
    return {
        'name': name,
        'exists': True,
        'size_bytes': len(data),
        'sha256': actual_sha256,
        'matches_expected': (hmac.compare_digest(actual_sha256, expected_sha256)
                             if expected_sha256 is not None else None),
        'read_only': True
    }



def _validate_backup_name(name: str) -> str:
    if not isinstance(name, str) or not BACKUP_FILENAME.fullmatch(name):
        raise ValueError('Nur einfache Gateway-Backup-Dateinamen (*.yaml.bak) erlaubt.')
    return name


def _validate_expected_hash(expected_sha256: str | None) -> None:
    if expected_sha256 is not None and (
        not isinstance(expected_sha256, str) or
        re.fullmatch(r'[0-9a-f]{64}', expected_sha256) is None
    ):
        raise ValueError('Ungültiger erwarteter SHA256 (64 Kleinbuchstaben/Hex-Zeichen).')


def list_backups(limit: int = 50) -> dict:
    """Return only metadata for regular gateway backups, never file contents.

    Directory access uses the same no-follow descriptor as verify_backup.
    Never follow file symlinks, and never return arbitrary filenames.
    """
    if type(limit) is not int or not 1 <= limit <= 100:
        raise ValueError('limit muss eine Ganzzahl zwischen 1 und 100 sein.')
    fd = _open_backup_dir()
    try:
        results = []
        with os.scandir(fd) as entries:
            for entry in entries:
                if not BACKUP_FILENAME.fullmatch(entry.name):
                    continue
                # dir_fd-based, non-following stat, no symlink/directory/FIFO exposure.
                try:
                    info = os.stat(entry.name, dir_fd=fd, follow_symlinks=False)
                except FileNotFoundError:
                    continue
                if stat.S_ISREG(info.st_mode):
                    results.append({'name': entry.name, 'size_bytes': info.st_size})
        results.sort(key=lambda r: r['name'], reverse=True)
        return {
            'backups': results[:limit],
            'count': min(len(results), limit),
            'truncated': len(results) > limit,
            'read_only': True,
        }
    finally:
        os.close(fd)


def read_backup(name: str, expected_sha256: str | None = None) -> dict:
    """Read a specific gateway-created YAML backup only after explicit request.

    File is opened no-follow and non-blocking, verified regular, read at most
    MAX_BYTES, verified against the caller's expected SHA256 before disclosure.
    """
    _validate_backup_name(name)
    _validate_expected_hash(expected_sha256)
    fd = _open_backup_dir()
    try:
        try:
            data = _read_at(fd, name)
        except FileNotFoundError:
            return {'name': name, 'exists': False, 'read_only': True}
    finally:
        os.close(fd)
    hash_value = digest(data)
    if expected_sha256 is not None and not hmac.compare_digest(hash_value, expected_sha256):
        raise ValueError('Backup-SHA256 stimmt nicht mit dem erwarteten Wert überein.')
    try:
        content = data.decode('utf-8', errors='strict')
    except UnicodeDecodeError as exc:
        raise ValueError('Backup ist kein gültiger UTF-8-Text.') from exc
    return {
        'name': name,
        'exists': True,
        'size_bytes': len(data),
        'sha256': hash_value,
        'content': content,
        'read_only': True,
        'sensitive_content_warning': 'Backup-Inhalt kann Zugangsdaten enthalten; nicht ungeprüft weitergeben.',
    }

def _one_time_approval(name: str, expected_sha256: str | None, proposed_sha256: str) -> str:
    """Check a value set separately in the Home Assistant app's config UI.

    The MCP client cannot supply the authorization; the authorizing user must
    set APPROVED_CHANGE in the supervisor-managed options and restart the app.
    """
    options_file = '/data/options.json'
    fd = os.open(options_file, os.O_RDONLY | os.O_NOFOLLOW)
    try:
        with os.fdopen(fd, 'r', encoding='utf-8') as stream:
            options = json.load(stream)
    finally:
        pass
    approved = read_approval(options_file) if unified_mode() else options.get('APPROVED_CHANGE', '')
    expected = f'{name}|{expected_sha256 or "NEW"}|{proposed_sha256}'
    if unified_mode():
        expected = 'YAML|' + expected
    if not isinstance(approved, str) or not hmac.compare_digest(approved, expected):
        raise PermissionError('Einmalige Bestätigung in den HA-App-Einstellungen fehlt oder stimmt nicht.')
    return expected


def _approval_ledger_begin(approval_key: str):
    """Lock the local approval ledger and reject reuse, including after restarts."""
    lock = os.open('/data/approvals.lock', os.O_CREAT | os.O_RDWR | os.O_NOFOLLOW, 0o600)
    fcntl.flock(lock, fcntl.LOCK_EX)
    used_path = '/data/approvals_used.json'
    try:
        try:
            rfd = os.open(used_path, os.O_RDONLY | os.O_NOFOLLOW)
        except FileNotFoundError:
            used = []
        else:
            with os.fdopen(rfd, 'r', encoding='utf-8') as r:
                used = json.load(r)
        if not isinstance(used, list) or any(not isinstance(e, str) for e in used):
            raise ValueError('Freigabeprotokoll beschädigt; Schreibvorgang gesperrt.')
        key_hash = digest(approval_key.encode('utf-8'))
        if key_hash in used:
            raise PermissionError('Diese Freigabe wurde bereits verbraucht.')
        return lock, used, key_hash
    except BaseException:
        os.close(lock)
        raise


def _approval_ledger_finish(used: list[str], key_hash: str) -> None:
    """Durably mark approval as consumed; fail closed on ledger write errors."""
    path = '/data/approvals_used.json'
    temporary = '/data/approvals_used.json.tmp'
    fd = os.open(temporary, os.O_WRONLY | os.O_CREAT | os.O_TRUNC | os.O_NOFOLLOW, 0o600)
    with os.fdopen(fd, 'w', encoding='utf-8') as dest:
        json.dump(used + [key_hash], dest)
        dest.flush()
        os.fsync(dest.fileno())
    os.replace(temporary, path)
    dirfd = os.open('/data', os.O_RDONLY | os.O_DIRECTORY)
    try:
        os.fsync(dirfd)
    finally:
        os.close(dirfd)


def commit_write(name: str, content: str, expected_sha256: str | None,
                 proposed_sha256: str, approval: str) -> dict:
    if os.environ.get('WRITE_ENABLED', 'false').lower() != 'true':
        raise PermissionError('Schreibmodus gesperrt. Aktivierung nur über HA-App-Konfiguration.')
    _validate_write_name(name)
    _syntax(content)
    data = content.encode('utf-8')
    if not isinstance(proposed_sha256, str) or proposed_sha256 != digest(data):
        raise ValueError('Vorschlag-Hash stimmt nicht mit Inhalt überein.')
    # This is an additional explicit tool argument, NOT a substitute for a real user approval.
    if approval != f'FREIGABE {name} {proposed_sha256}':
        raise PermissionError('Exakte Freigabe für Dateiname und SHA256 erforderlich.')
    if expected_sha256 is not None and (not isinstance(expected_sha256, str) or
        not re.fullmatch(r'[0-9a-f]{64}', expected_sha256)):
        raise ValueError('Ungültiger Original-Hash.')

    approval_key = _one_time_approval(name, expected_sha256, proposed_sha256)
    ledger_fd, used_approvals, approval_hash = _approval_ledger_begin(approval_key)
    try:
        result = _commit_approved(name, data, expected_sha256, proposed_sha256, ledger_fd, used_approvals, approval_hash)
        # Retention is optional housekeeping and must NEVER break the existing
        # successful commit or prevent its consumed approval from being cleared.
        try:
            from backup_retention_commit_stage4 import after_successful_commit
            result['retention'] = after_successful_commit(
                result, package_name=name, original_sha256=expected_sha256,
                backup_dir=ROOT / BACKUP_DIR,
                mode=os.environ.get('GW_RETENTION_STAGE4_MODE', 'off'),
            )
        except Exception:
            _LOG.warning('Backup-Retention-Modul nicht verfügbar; Commit bleibt gültig.')
            result['retention'] = {'status': 'failed', 'reason': 'integration_error'}
        # Always attempt cleanup even after housekeeping errors. The existing
        # persistent ledger separately blocks any reused one-time approval.
        result['approval_field_cleared'] = _clear_used_approval(approval_key)
        return result
    finally:
        os.close(ledger_fd)



def _clear_used_approval(approval_key: str) -> bool:
    if unified_mode():
        return clear_approval(approval_key)
    """Clear only the just-consumed HA app option through Supervisor, after commit.

    Fail non-destructively: if the Supervisor is unreachable or the option is
    already changed, leave the UI value alone. The persistent approval ledger
    already makes a consumed value unusable even when clearing fails.
    """
    token = os.environ.get('SUPERVISOR_TOKEN')
    if not token:
        _LOG.warning('Einmalfreigabe verbraucht; automatisches Leeren nicht verfügbar (Supervisor-Token fehlt).')
        return False
    base = 'http://supervisor/addons/self'
    headers = {'Authorization': 'Bearer ' + token, 'Accept': 'application/json'}
    try:
        request = urllib.request.Request(base + '/options/config', headers=headers, method='GET')
        with urllib.request.urlopen(request, timeout=4) as response:
            body = json.load(response)
        if not isinstance(body, dict) or body.get('result') != 'ok':
            raise ValueError('Supervisor-Konfigurationsantwort ungültig')
        options = body.get('data')
        if not isinstance(options, dict):
            raise ValueError('Supervisor-Konfigurationsdaten ungültig')
        actual = options.get('APPROVED_CHANGE')
        if not isinstance(actual, str) or not hmac.compare_digest(actual, approval_key):
            # Do not erase a different approval that the user just entered.
            _LOG.warning('Freigabefeld wurde geändert; automatisches Leeren ausgelassen.')
            return False
        # Supervisor's POST /addons/self/options validates/replaces the entire options
        # object; sending only APPROVED_CHANGE may fail schema validation or discard
        # credentials. Preserve every other setting from the validated self GET.
        new_options = dict(options)
        new_options['APPROVED_CHANGE'] = ''
        payload = json.dumps({'options': new_options}).encode('utf-8')
        request = urllib.request.Request(base + '/options', data=payload,
            headers={**headers, 'Content-Type': 'application/json'}, method='POST')
        with urllib.request.urlopen(request, timeout=4) as response:
            answer = json.load(response)
        if not isinstance(answer, dict) or answer.get('result') != 'ok':
            raise ValueError('Supervisor hat Änderung nicht bestätigt')
        # GET-after-POST is essential: HTTP 200 / result=ok alone does not
        # prove the visible option has actually been cleared.
        request = urllib.request.Request(base + '/options/config', headers=headers, method='GET')
        with urllib.request.urlopen(request, timeout=4) as response:
            verified = json.load(response)
        cleared = (isinstance(verified, dict) and verified.get('result') == 'ok'
                   and isinstance(verified.get('data'), dict)
                   and verified['data'].get('APPROVED_CHANGE') == '')
        if not cleared:
            _LOG.warning('YAML-Freigabe nach Supervisor-Antwort nicht als leer bestätigt.')
            return False
        _LOG.info('Benutzte Einmalfreigabe nach erneutem Lesen als leer bestätigt.')
        return True
    except urllib.error.HTTPError as exc:
        # The status (but never the body or URL) is enough to distinguish
        # 400/422 validation errors from 401/403 permission problems.
        _LOG.warning('Automatisches Leeren von APPROVED_CHANGE fehlgeschlagen (HTTP %d).', exc.code)
        return False
    except (OSError, ValueError, urllib.error.URLError, TimeoutError) as exc:
        # Never log credentials, approval values, HTTP response bodies or tokens.
        _LOG.warning('Automatisches Leeren von APPROVED_CHANGE fehlgeschlagen (%s).', type(exc).__name__)
        return False

class Sha256ConflictError(ValueError):
    """User-readable conflict with explicit, local side-effect facts.

    The facts describe THIS Gateway invocation only, not concurrent external edits.
    Approval state is recorded only after durable ledger finalization.
    """

    def __init__(self, reason: str, *, expected_sha256: str | None,
                 actual_sha256: str | None, backup_name: str | None = None,
                 approval_consumed: bool = False):
        self.details = {
            'error_code': 'SHA256_CONFLICT',
            'reason': reason,
            'expected_sha256': expected_sha256,
            'actual_sha256': actual_sha256,
            'backup_created': backup_name is not None,
            'backup': f'yaml_backups/{backup_name}' if backup_name else None,
            'approval_consumed': approval_consumed,
            'file_written': False,
            'next_step': 'Aktuelle YAML-Datei neu lesen und Änderung erneut planen; neue Einmalfreigabe verwenden.'
                         if approval_consumed else
                         'Aktuelle YAML-Datei neu lesen, Änderung erneut planen; bestehende Freigabe nicht ungeprüft verwenden.',
        }
        super().__init__(
            f"SHA256-Konflikt: {reason}. Erwartet: {expected_sha256 or 'NEW'}; "
            f"aktuell: {actual_sha256 or 'NICHT_VORHANDEN'}; "
            f"Backup erstellt: {'ja' if backup_name else 'nein'}; "
            f"Einmalfreigabe verbraucht: {'ja' if approval_consumed else 'nein'}; "
            'YAML durch diesen Vorgang nicht überschrieben. '
            + self.details['next_step'])


def _commit_approved(name, data, expected_sha256, proposed_sha256, ledger_fd, used_approvals, approval_hash):
    fd = _open_dir(ROOT / PACKAGE_DIR)
    backup_name = None
    approval_consumed = False
    try:
        # _approval_ledger_begin() holds an exclusive flock on /data/approvals.lock
        # for the entire commit_write() call. This serializes gateway writes.
        # Do not flock the package-directory fd: HAOS/AppArmor denies that operation.
        # External edits are still guarded by original SHA256 and pre-replace checks.
        try:
            old = _read_at(fd, name)
            existed = True
        except FileNotFoundError:
            old = b''
            existed = False
        current_sha = digest(old) if existed else None
        if existed:
            if expected_sha256 is None:
                raise Sha256ConflictError('Datei wurde seit der Vorschau angelegt',
                    expected_sha256=expected_sha256, actual_sha256=current_sha)
            if expected_sha256 != current_sha:
                raise Sha256ConflictError('Datei wurde seit der Vorschau verändert',
                    expected_sha256=expected_sha256, actual_sha256=current_sha)
        elif expected_sha256 is not None:
            raise Sha256ConflictError('Datei wurde seit der Vorschau entfernt',
                expected_sha256=expected_sha256, actual_sha256=None)

        bfd = _open_backup_dir()
        try:
            stamp = dt.datetime.now(dt.timezone.utc).astimezone().strftime('%Y-%m-%d_%H-%M-%S_%f')
            if existed:
                backup_name = f'{name[:-5]}_{stamp}.yaml.bak'
                _write_new_at(bfd, backup_name, old)
            else:
                # New files have no prior contents to back up. Record creation before writing.
                backup_name = f'{name[:-5]}_{stamp}.created.json'
                manifest = json.dumps({'action': 'create', 'name': name,
                                       'proposed_sha256': proposed_sha256,
                                       'at': stamp}, ensure_ascii=False).encode('utf-8')
                _write_new_at(bfd, backup_name, manifest)
            os.fsync(bfd)
            _approval_ledger_finish(used_approvals, approval_hash)
            approval_consumed = True
        finally:
            os.close(bfd)

        temp_name = f'.{name}.{os.getpid()}.{os.urandom(8).hex()}.tmp'
        try:
            _write_new_at(fd, temp_name, data)
            try:
                current = _read_at(fd, name)
                current_exists = True
            except FileNotFoundError:
                current, current_exists = b'', False
            if current_exists != existed or (existed and current != old):
                raise Sha256ConflictError('Datei während des Schreibens verändert',
                    expected_sha256=expected_sha256,
                    actual_sha256=digest(current) if current_exists else None,
                    backup_name=backup_name, approval_consumed=approval_consumed)
            os.replace(temp_name, name, src_dir_fd=fd, dst_dir_fd=fd)
            os.fsync(fd)
        finally:
            try:
                os.unlink(temp_name, dir_fd=fd)
            except FileNotFoundError:
                pass
    finally:
        os.close(fd)
    return {'written': f'packages/{name}', 'sha256': digest(data),
            'backup': f'yaml_backups/{backup_name}',
            'note': 'YAML-Syntax geprüft; Home-Assistant-Konfigurationsprüfung/Reload separat.'}
